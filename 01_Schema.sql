CREATE TABLE Users(UserId INT IDENTITY PRIMARY KEY, FullName NVARCHAR(100) NOT NULL, Email NVARCHAR(150) NOT NULL UNIQUE, Role NVARCHAR(30) NOT NULL DEFAULT 'Developer');
CREATE TABLE Priorities(PriorityId TINYINT PRIMARY KEY, Name NVARCHAR(20) NOT NULL, SlaHours INT NOT NULL);
INSERT Priorities VALUES (1,'Critical',4),(2,'High',24),(3,'Medium',72),(4,'Low',168);
CREATE TABLE Defects(
 DefectId INT IDENTITY PRIMARY KEY,
 Title NVARCHAR(200) NOT NULL,
 Description NVARCHAR(MAX) NULL,
 Status NVARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (Status IN ('Open','In Progress','Resolved','Closed')),
 PriorityId TINYINT NOT NULL REFERENCES Priorities(PriorityId),
 ReportedBy INT NOT NULL REFERENCES Users(UserId),
 AssignedTo INT NULL REFERENCES Users(UserId),
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
 ResolvedAt DATETIME2 NULL,
 ClosedAt DATETIME2 NULL,
 SlaDueAt DATETIME2 NULL,
 ReopenCount INT NOT NULL DEFAULT 0);
CREATE TABLE DefectAudit(AuditId INT IDENTITY PRIMARY KEY, DefectId INT NOT NULL, OldStatus NVARCHAR(20), NewStatus NVARCHAR(20), ChangedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), ChangedBy SYSNAME NOT NULL DEFAULT SUSER_SNAME());
GO
